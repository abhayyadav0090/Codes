/*
Write a program to check whether a number is divisible by 97 or not.
*/

#include <stdio.h>

int main() {
    int a = 2342354;
    printf("The value of a%%97 is %d", a%97);
    // if it printd 0 then it is divisible
    // otherwise not divisible
    return 0;
}